-- Esquema PostgreSQL (Neon en produccion, contenedor postgres en local).
-- Es idempotente: se puede ejecutar varias veces sin perder datos.
--
-- Decisiones respecto al esquema MySQL anterior:
--  * CITEXT en correo, nombre_usuario y placa: MySQL comparaba sin distinguir
--    mayusculas (utf8mb4_unicode_ci) y la API depende de ello.
--  * activo/activa siguen siendo SMALLINT 0/1: el frontend compara con 0 y 1.
--  * Las fechas son TIMESTAMPTZ para no depender de la zona horaria del servidor.
--  * ENUM se reemplaza por TEXT + CHECK.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS usuario (
  id_usuario     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR(100) NOT NULL,
  nombre_usuario CITEXT       NOT NULL UNIQUE,
  correo         CITEXT       NOT NULL UNIQUE,
  password_hash  VARCHAR(255) NOT NULL,
  tipo_usuario   TEXT         NOT NULL DEFAULT 'estudiante'
                 CHECK (tipo_usuario IN ('admin','conductor','estudiante')),
  activo         SMALLINT     NOT NULL DEFAULT 1,
  fecha_creacion TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS bus (
  id_bus       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       VARCHAR(100) NOT NULL,
  placa        CITEXT       NOT NULL UNIQUE,
  capacidad    INT          NOT NULL DEFAULT 45,
  estado       TEXT         NOT NULL DEFAULT 'inactivo'
               CHECK (estado IN ('en_recorrido','detenido','fuera_de_servicio','inactivo')),
  id_conductor INT NULL REFERENCES usuario(id_usuario) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS ruta (
  id_ruta     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(100) NOT NULL,
  descripcion TEXT NULL,
  activa      SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS parada (
  id_parada INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre    VARCHAR(100) NOT NULL,
  latitud   DECIMAL(10,7) NOT NULL,
  longitud  DECIMAL(10,7) NOT NULL,
  activa    SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS ruta_parada (
  id_ruta   INT NOT NULL REFERENCES ruta(id_ruta)     ON DELETE CASCADE,
  id_parada INT NOT NULL REFERENCES parada(id_parada) ON DELETE CASCADE,
  orden     INT NOT NULL,
  PRIMARY KEY (id_ruta, id_parada)
);

CREATE TABLE IF NOT EXISTS bus_ruta (
  id_bus  INT NOT NULL REFERENCES bus(id_bus)   ON DELETE CASCADE,
  id_ruta INT NOT NULL REFERENCES ruta(id_ruta) ON DELETE CASCADE,
  PRIMARY KEY (id_bus, id_ruta)
);

CREATE TABLE IF NOT EXISTS horario (
  id_horario   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ruta      INT  NOT NULL REFERENCES ruta(id_ruta) ON DELETE CASCADE,
  hora_salida  TIME NOT NULL,
  hora_llegada TIME NOT NULL
);

CREATE TABLE IF NOT EXISTS ubicacion_bus (
  id_ubicacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_bus       INT NOT NULL REFERENCES bus(id_bus) ON DELETE CASCADE,
  latitud      DECIMAL(10,7) NOT NULL,
  longitud     DECIMAL(10,7) NOT NULL,
  fecha_hora   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_bus_fecha ON ubicacion_bus (id_bus, fecha_hora);

CREATE TABLE IF NOT EXISTS notificacion (
  id_notificacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ruta         INT NULL REFERENCES ruta(id_ruta)       ON DELETE CASCADE,
  id_conductor    INT NULL REFERENCES usuario(id_usuario) ON DELETE SET NULL,
  tipo            TEXT NOT NULL DEFAULT 'info'
                  CHECK (tipo IN ('cambio_ruta','retraso','info')),
  mensaje         TEXT NOT NULL,
  fecha_hora      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS favoritos (
  id_usuario INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  id_ruta    INT NOT NULL REFERENCES ruta(id_ruta)       ON DELETE CASCADE,
  PRIMARY KEY (id_usuario, id_ruta)
);
